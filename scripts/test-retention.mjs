process.env.DATA_DIR="data/test-out/retention-tests";
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const {jobDir}=await import("../src/media.js");
const {pruneTemplateMedia}=await import("../src/media-retention.js");
const now=Date.now(),old=now-8*86400000;
for(const [dir,file]of [["_test-finished","raw.media"],["_test-finished","out.mp4"],["edit-_test-finished","raw.media"],["edit-_test-active","live.media"],["_test-legacy","old.media"]])fs.writeFileSync(path.join(jobDir(dir),file),"fixture");
const db={jobs:[{id:"_test-finished",templateId:"product-presenter",status:"done",finishedAt:old,templateData:{assets:[{id:"raw",file:"raw.media"}]}},{id:"_test-legacy",status:"done",finishedAt:old,inputs:[{file:"old.media"}]}],edits:[{id:"_test-finished",jobId:"_test-finished",assets:[{id:"raw",file:"raw.media"}]},{id:"_test-active",assets:[{id:"live",file:"live.media"}]}]};
assert.equal(pruneTemplateMedia(db,now),2);
assert(fs.existsSync(path.join(jobDir("_test-finished"),"out.mp4")));
assert(fs.existsSync(path.join(jobDir("edit-_test-active"),"live.media")));
assert(fs.existsSync(path.join(jobDir("_test-legacy"),"old.media")));
assert(db.edits[0].mediaExpired);
assert.equal(pruneTemplateMedia(db,now),0);
const ad=jobDir('_test-ad-preview');fs.mkdirSync(path.join(ad,'ad-assets'),{recursive:true});fs.writeFileSync(path.join(ad,'raw.media'),'fixture');fs.writeFileSync(path.join(ad,'ad-assets','subject.png'),'fixture');
const active={jobs:[{id:'_test-ad-preview',templateId:'photo-motion',isPreview:true,status:'done',finishedAt:old,templateData:{adVersion:2,assets:[{file:'raw.media'}]}}],edits:[{id:'ad-draft',previewJobId:'_test-ad-preview',assets:[]}]};
assert.equal(pruneTemplateMedia(active,now),0);assert(fs.existsSync(path.join(ad,'ad-assets','subject.png')));
active.edits[0].archived=true;assert.equal(pruneTemplateMedia(active,now),2);assert(!fs.existsSync(path.join(ad,'ad-assets')));
console.log("10 retention checks passed: active drafts/preview assets preserved; finished sources cleaned.");
